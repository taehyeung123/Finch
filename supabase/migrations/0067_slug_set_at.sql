-- 0067_slug_set_at.sql — 주소를 「사용자가 직접 정한」 마지막 시각 (2026-08-26 사장님 결정)
--
-- 배경: 템플릿/가져오기로 시작하면 주소가 무작위(6kt139hq 류)로 깔린다. 이제 앱이
-- 최초 진입에서 「주소 정하기」 모달을 띄우고, 정한 뒤에는 30일에 한 번만 바꿀 수 있다
-- (정한 직후 10분은 오타 수정 유예). 판별과 쿨다운의 기준이 이 컬럼 하나다:
--
--   null      = 사용자가 주소를 정한 적 없음(무작위 그대로) → 모달을 띄우고, 변경은 자유
--   timestamp = 마지막으로 직접 정한 시각 → 30일 쿨다운의 기준점
--
-- 기존 행은 전부 null 로 남는다 — 의도된 것이다. 이미 쓰는 사람들도 「주소 정하기」
-- 기회를 한 번 받는 게 맞다(지금까지는 전원이 무작위 주소로 시작했다).
--
-- 쿨다운 검사는 앱(actions.ts)이 한다. DB check 로 굳히지 않는 이유: 유예(10분)·기간(30일)은
-- 정책값이라 바뀔 수 있고, 마이그레이션 전 DB 에서도 앱이 계단식 폴백으로 동작해야 한다.

alter table public.link_pages add column if not exists slug_set_at timestamptz;

comment on column public.link_pages.slug_set_at is
  '사용자가 주소를 직접 정한 마지막 시각. null=아직 안 정함(무작위) → 앱이 최초 「주소 정하기」 모달을 띄운다. 30일 쿨다운의 기준점(app/(finch)/(app)/links/actions.ts).';
