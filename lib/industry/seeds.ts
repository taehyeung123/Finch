export function allSeedKeywords(): SeedKeyword[] {
  const out: SeedKeyword[] = [];
  for (const [industryId, ads, organic] of TABLE) {
    // 앞쪽 키워드가 그 업종의 대표어다. 순서대로 가중치를 내려 첫 바퀴 순서를 만든다.
    ads.forEach((keyword, i) => {
      out.push({ industryId, platform: "meta_ads", keyword, weight: 200 - i * 5 });
    });
    organic.forEach((keyword, i) => {
      out.push({ industryId, platform: "instagram", keyword, weight: 140 - i * 5 });
    });
  }
  return out;
}
