export interface BrandSeed {
  industryId: string;
  keyword: string;
  weight: number;
}

/** 브랜드 시드는 weight 300대 — 일반 시드(200대)보다 항상 먼저 돈다 */
export function allBrandSeeds(): BrandSeed[] {
  const out: BrandSeed[] = [];
  for (const [industryId, brands] of BRAND_TABLE) {
    brands.forEach((keyword, i) => {
      out.push({ industryId, keyword, weight: 340 - i * 5 });
    });
  }
  return out;
}
