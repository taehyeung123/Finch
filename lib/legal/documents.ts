/* ── 기존 이름 호환 — 조항 배열만 필요한 곳 ── */
export const TERMS_SECTIONS: readonly LegalSection[] = TERMS_DOC.sections;
export const OPERATION_SECTIONS: readonly LegalSection[] = OPERATION_DOC.sections;
export const PRIVACY_SECTIONS: readonly LegalSection[] = PRIVACY_DOC.sections;

/** 약관에서 조항 몇 개만 — 환불정책 페이지가 제22~29조를 그대로 가져간다(본문 두 벌 금지) */
export function pickTermsSections(ids: readonly string[]): LegalSection[] {
  return ids
    .map((id) => TERMS_DOC.sections.find((s) => s.id === id))
    .filter((s): s is LegalSection => Boolean(s))
    /* 장 제목은 원래 문서의 흐름에서만 뜻이 있다 — 모아 보여 줄 땐 뗀다 */
    .map((s) => ({ ...s, chapter: undefined }));
}
